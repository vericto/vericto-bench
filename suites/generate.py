"""Writes the campaign suites of BENCH-2026-11 (design section 10) as TOML.

    python3 suites/generate.py      # rewrites quick.toml, published.toml, day2.toml, c7i.toml

The TOML files are the pre-registered plan and are committed; this script only
keeps them consistent. Change the matrix here, regenerate, and commit both.
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
PG6 = ["direct", "haproxy-tcp", "pgbouncer-session", "vericto-offline", "vericto-enforce", "vericto-observe"]
MY6 = ["direct", "haproxy-tcp", "proxysql", "vericto-offline", "vericto-enforce", "vericto-observe"]
HEAD = ["direct", "haproxy-tcp", "vericto-enforce"]
CURVE_RATES = [10, 30, 50, 70, 80, 90, 100]  # % of S (design section 8, "Rates")
SAT_CONC = [1, 2, 4, 8, 16, 32, 64, 128]

HEADER = """# SPDX-FileCopyrightText: 2026 Vericto S.A.S.
# SPDX-License-Identifier: Apache-2.0
#
# {title}
# Generated by suites/generate.py from the design's matrix (BENCH-2026-11 section 10).
# Pre-registered: do not edit between the start of a campaign and its report.
"""


def toml_value(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, str):
        return f'"{v}"'
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    return str(v)


def curve(**kw):
    return kw


def render(title, suite, datasets, curves, extra=""):
    out = [HEADER.format(title=title), "[suite]"]
    out += [f"{k} = {toml_value(v)}" for k, v in suite.items()]
    out += ["", "[datasets]"] + [f"{k} = {toml_value(v)}" for k, v in datasets.items()]
    out += ["", extra] if extra else []
    for c in curves:
        comment = c.pop("_comment", None)
        out.append("")
        if comment:
            out.append(f"# {comment}")
        out.append("[[curve]]")
        out += [f"{k} = {toml_value(v)}" for k, v in c.items()]
    return "\n".join(out) + "\n"


def sat_curves(sizes, reps=1):
    cs = []
    for size in sizes:
        tag = size.replace(".", "")
        cs.append(curve(_comment=f"P-sat: closed-loop saturation, W1 select-only extended, TLS, {size} vCPU",
                        id=f"sat-pg-w1-{tag}", engine="pg", tool="pgbench", workload="select-only", mode="extended",
                        tls=True, size=size, targets=PG6, loop="closed", concurrency=SAT_CONC, warmup_s=30, duration_s=120, reps=reps))
        cs.append(curve(_comment=f"P-sat: closed-loop saturation, W3 oltp_read_only replay (text), TLS, {size} vCPU",
                        id=f"sat-my-w3-{tag}", engine="mysql", tool="vbench", workload="sysbench-ro", mode="text",
                        tls=True, size=size, targets=MY6, loop="closed", concurrency=SAT_CONC, warmup_s=30, duration_s=120, reps=reps))
    return cs


def head_curves(size, rates=CURVE_RATES, reps=None, suffix=""):
    tag = size.replace(".", "")
    pg = curve(_comment=f"P-head-pg: HEADLINE PG curve, W1 pgbench select-only, extended protocol, TLS, {size} vCPU",
               id=f"head-pg-w1-{tag}{suffix}", engine="pg", tool="pgbench", workload="select-only", mode="extended", tls=True,
               size=size, targets=HEAD, rates_pct=rates, saturation_from=f"sat-pg-w1-{tag}", conns=64)
    my = curve(_comment=f"P-head-my: HEADLINE MySQL curve, W3 oltp_read_only (vbench replay, text protocol), TLS, {size} vCPU",
               id=f"head-my-w3-{tag}{suffix}", engine="mysql", tool="vbench", workload="sysbench-ro", mode="text", tls=True,
               size=size, targets=HEAD, rates_pct=rates, saturation_from=f"sat-my-w3-{tag}")
    if reps:
        pg["reps"] = my["reps"] = reps
    return [pg, my]


# Budget trim of day 1 (owner rule, 2026-10-19: P1 + P2 under about USD 45 of
# AWS spend, about USD 0.51/h for both hosts and the NAT gateway). In the owner's
# order: (1) the c7i cross-check is not run; (2) every non-headline open-loop
# curve runs NONHEAD_REPS interleaved repetitions instead of 3; (3) the two
# headline curves keep 3. Closed-loop saturation curves already run 1.
NONHEAD_REPS = 2
# Run order (pre-registered with the suite): saturation first (it sets S), the
# generator validation next (a pre-flight, design section 8), then the curves
# the day-1 report needs most, so a stop by the runtime guard loses the least.
ORDER = ["sat-", "validate-", "head-pg-w1-05", "head-my-w3-05", "decomp-", "size-", "bytes-", "blocked-", "conn-",
         "tlsoff-", "modes-", "orm-", "head-pg-w1-1", "head-my-w3-1", "h2-"]


def _rank(cid):
    for i, pre in enumerate(ORDER):
        if cid == pre or cid.startswith(pre):
            return i
    return len(ORDER)


# Day 1's S (closed-loop maximum of vericto-enforce at 0.5 vCPU, TLS) from run
# bench-2026-11-p2-day1 (cells.jsonl: sat-pg-w1-05 c8, sat-my-w3-05 c4), so day 2
# runs the headline curves at exactly day 1's absolute rates.
DAY1_S = {"head-pg-w1-05": 6032.566666666667, "head-my-w3-05": 356.59166666666664}


def day2_curves():
    out = []
    for c in head_curves("0.5", suffix="-day2"):
        base = c["id"][: -len("-day2")]
        # Owner decision 2026-10-20: day 2 runs 1 repetition (day-to-day and
        # host-to-host stability against day 1's intervals), about 4.6 hours.
        out.append(dict(c, saturation_from="", saturation_qps=DAY1_S.get(base, 0), reps=1))
    return out


def published_trimmed():
    cs = published()
    for c in cs:
        if c.get("loop", "open") == "open" and not c["id"].startswith(("head-pg-w1-05", "head-my-w3-05")):
            c["reps"] = NONHEAD_REPS
    # sat-pg-w2 / sat-pg-w4 / sat-my-w4 are closed loop and set the rates of
    # their own curves: keep them with the saturation block.
    return sorted(cs, key=lambda c: _rank(c["id"]))  # stable: the design order within a block


def published():
    cs = sat_curves(["0.5", "1"])
    cs.append(curve(_comment="sysbench oltp_read_only and read_write, closed loop (standard throughput figures, prepared "
                             "statements; TLS off: sysbench 1.0.20 cannot do unverified TLS)",
                    id="sat-my-sysbench-ro", engine="mysql", tool="sysbench", workload="oltp_read_only", tls=False, size="0.5",
                    targets=MY6, loop="closed", concurrency=SAT_CONC, warmup_s=30, duration_s=120, reps=1))
    cs.append(curve(id="sat-my-sysbench-rw", engine="mysql", tool="sysbench", workload="oltp_read_write", tls=False, size="0.5",
                    targets=["direct", "haproxy-tcp", "vericto-enforce"], loop="closed", concurrency=SAT_CONC, warmup_s=30,
                    duration_s=120, reps=1))
    cs += head_curves("0.5")
    cs.append(curve(_comment="P-decomp: every target at 30% and 70% of S: hop, protocol, evaluation, telemetry, observe",
                    id="decomp-pg-w1", engine="pg", tool="pgbench", workload="select-only", mode="extended", tls=True, size="0.5",
                    targets=PG6, rates_pct=[30, 70], saturation_from="sat-pg-w1-05", conns=64))
    cs.append(curve(id="decomp-my-w3", engine="mysql", tool="vbench", workload="sysbench-ro", mode="text", tls=True, size="0.5",
                    targets=MY6, rates_pct=[30, 70], saturation_from="sat-my-w3-05"))
    for mode in ("simple", "prepared"):
        cs.append(curve(_comment=f"P-modes: W1 {mode}", id=f"modes-pg-w1-{mode}", engine="pg", tool="pgbench", workload="select-only",
                        mode=mode, tls=True, size="0.5", targets=HEAD, rates_pct=[30, 70], saturation_from="sat-pg-w1-05", conns=64))
    cs.append(curve(_comment="P-modes: W2 tpcb-like saturation (write-bound) for its own rates", id="sat-pg-w2", engine="pg",
                    tool="pgbench", workload="tpcb-like", mode="extended", tls=True, size="0.5", targets=["direct", "vericto-enforce"],
                    loop="closed", concurrency=SAT_CONC, warmup_s=30, duration_s=120, reps=1))
    for mode in ("simple", "extended", "prepared"):
        cs.append(curve(id=f"modes-pg-w2-{mode}", engine="pg", tool="pgbench", workload="tpcb-like", mode=mode, tls=True, size="0.5",
                        targets=HEAD, rates_pct=[30, 70], saturation_from="sat-pg-w2", conns=64))
    for eng, mode, sat in (("pg", "extended", "sat-pg-w4"), ("mysql", "text", "sat-my-w4")):
        cs.append(curve(_comment=f"P-orm: W4 ORM mix ({eng}) saturation, then 3 rates", id=sat, engine=eng, tool="vbench",
                        workload="orm", mode=mode, tls=True, size="0.5", targets=["direct", "vericto-enforce"], loop="closed",
                        concurrency=SAT_CONC, warmup_s=30, duration_s=120, reps=1))
        cs.append(curve(id=f"orm-{eng}-w4", engine=eng, tool="vbench", workload="orm", mode=mode, tls=True, size="0.5",
                        targets=["direct", "vericto-enforce"], rates_pct=[30, 50, 70], saturation_from=sat))
    cs.append(curve(_comment="P-tls-off: headline targets at 30% and 70%, TLS off on both legs", id="tlsoff-pg-w1", engine="pg",
                    tool="pgbench", workload="select-only", mode="extended", tls=False, size="0.5", targets=HEAD,
                    rates_pct=[30, 70], saturation_from="sat-pg-w1-05", conns=64))
    cs.append(curve(id="tlsoff-my-w3", engine="mysql", tool="vbench", workload="sysbench-ro", mode="text", tls=False, size="0.5",
                    targets=HEAD, rates_pct=[30, 70], saturation_from="sat-my-w3-05"))
    cs += head_curves("1")
    # P-2tasks: the same absolute rates (% of S at 0.5 vCPU) for 1 x 0.5, 1 x 1 and 2 x 0.5.
    for size in ("0.5", "1", "2x0.5"):
        tag = size.replace(".", "")
        cs.append(curve(_comment=f"P-2tasks: {size}, same absolute rates (% of S at 0.5 vCPU)", id=f"h2-pg-w1-{tag}", engine="pg",
                        tool="pgbench", workload="select-only", mode="extended", tls=True, size=size,
                        targets=["direct", "vericto-enforce"], rates_pct=[30, 60, 90, 120, 150, 180],
                        saturation_from="sat-pg-w1-05", conns=128))
        cs.append(curve(id=f"h2-my-w3-{tag}", engine="mysql", tool="vbench", workload="sysbench-ro", mode="text", tls=True, size=size,
                        targets=["direct", "vericto-enforce"], rates_pct=[30, 60, 90, 120, 150, 180], saturation_from="sat-my-w3-05"))
    # P-size (W5): the ms/KB slope at 0.5 and 1 vCPU, 10 statements/s on one connection.
    for eng, mode in (("pg", "extended"), ("mysql", "text")):
        for size in ("0.5", "1"):
            tag = size.replace(".", "")
            for n in (1, 10, 100, 500, 1000, 2000):
                cs.append(curve(_comment=f"P-size: multi-row INSERT of {n} rows" if n == 1 else None, id=f"size-{eng}-batch{n}-{tag}",
                                engine=eng, tool="vbench", workload=f"batch{n}", mode=mode, tls=True, size=size,
                                targets=["direct", "vericto-enforce"], rates=[10], conns=1, warmup_s=10, duration_s=60))
            for n in ((10, 100, 1000, 10000) if size == "1" else ()):
                cs.append(curve(id=f"size-{eng}-inlist{n}-{tag}", engine=eng, tool="vbench", workload=f"inlist{n}", mode=mode,
                                tls=True, size=size, targets=["direct", "vericto-enforce"], rates=[10], conns=1,
                                warmup_s=10, duration_s=60))
    # P-blocked (W6): a block against a forward, end to end.
    for eng, mode in (("pg", "extended"), ("mysql", "text")):
        for w in ("blocked-delete", "delete-where", "blocked-update", "update-where"):
            cs.append(curve(_comment="P-blocked: blocked statement vs the same with a WHERE" if w == "blocked-delete" else None,
                            id=f"blocked-{eng}-{w}", engine=eng, tool="vbench", workload=w, mode=mode, tls=True, size="0.5",
                            targets=["direct", "vericto-enforce", "vericto-observe"], rates=[100], warmup_s=10, duration_s=60))
    # P-conn (W7): connect + TLS + authentication + one PK lookup per request.
    for eng, tgs in (("pg", ["direct", "haproxy-tcp", "pgbouncer-session", "vericto-offline", "vericto-enforce"]),
                     ("mysql", ["direct", "haproxy-tcp", "proxysql", "vericto-offline", "vericto-enforce"])):
        cs.append(curve(_comment="P-conn: connection setup" if eng == "pg" else None, id=f"conn-{eng}-w7", engine=eng, tool="vbench",
                        workload="connect", conn_mode="newconn", mode="extended" if eng == "pg" else "text", tls=True,
                        size="0.5", targets=tgs, rates=[20], warmup_s=10, duration_s=60))
    # P-bytes (W8): per-byte cost at reduced rates (traffic caps, section 8a).
    # PostgreSQL carries the full W8 matrix (the design's 108 cells); MySQL one
    # size, plain and masked, to show the masking path there too.
    for eng, mode, sizes in (("pg", "extended", (("10k", [200, 500, 1000]), ("100k", [20, 50, 100]), ("1m", [2, 5, 10]))),
                             ("mysql", "text", (("100k", [20, 50, 100]),))):
        for sz, rates in sizes:
            for masked in (False, True):
                w = f"payload-{sz}" + ("-masked" if masked else "")
                cs.append(curve(_comment="P-bytes: large results, plain and masked" if (sz == "10k" and not masked) else None,
                                id=f"bytes-{eng}-{w}", engine=eng, tool="vbench", workload=w, mode=mode, tls=True, size="0.5",
                                targets=["direct", "vericto-enforce"], rates=rates, warmup_s=30, duration_s=120))
    cs.append(curve(_comment="Generator validation: the database paused 1 s once a minute; p99.9/max must show ~1 s and ~1% of "
                             "requests above 500 ms", id="validate-generator-pg", engine="pg", tool="vbench", workload="select-only",
                    mode="extended", tls=True, size="0.5", targets=["direct"], rates=[1000], pause_every_s=60, pause_s=1))
    for c in cs:
        if c.get("_comment") is None:
            c.pop("_comment", None)
    return cs


